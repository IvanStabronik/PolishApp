/**
 * Prefer UK/BEL step chrome when L1 is ukr/bel, or when UK UI is selected.
 */
export function localizeStepTitle(
  titleRu: string,
  l1?: LearnerL1,
  uiLocale?: UiLocale | string | null,
): string {
  const key = norm(titleRu);
  const lang = resolveStepChromeLang(l1, uiLocale);
  if (lang === "uk") return TITLE_UK[key] ?? titleRu;
  if (lang === "bel") return TITLE_BEL[key] ?? titleRu;
  return titleRu;
}

/** Speaking prompt chrome — map known RU lines; unknown stays RU. */
export function localizeSpeakingPrompt(
  promptRu: string,
  l1?: LearnerL1,
  uiLocale?: UiLocale | string | null,
): string {
  const key = norm(promptRu);
  const lang = resolveStepChromeLang(l1, uiLocale);
  if (lang === "uk") return PROMPT_UK[key] ?? promptRu;
  if (lang === "bel") return PROMPT_BEL[key] ?? promptRu;
  return promptRu;
}
