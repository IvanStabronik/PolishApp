import type { LearnerL1, UiLocale } from "@/lib/enums";

export type StepChromeLang = "ru" | "uk" | "bel";

/**
 * Prefer L1 ukr/bel; if UI is Ukrainian and L1 is rus (or unset), use UK chrome.
 * Does not bulk-translate theory bodies — titles + speaking prompts only.
 */
export function resolveStepChromeLang(
  l1?: LearnerL1,
  uiLocale?: UiLocale | string | null,
): StepChromeLang {
  if (l1 === "ukr") return "uk";
  if (l1 === "bel") return "bel";
  const base = (uiLocale ?? "").toLowerCase().split("-")[0];
  if (base === "uk") return "uk";
  return "ru";
}

function norm(s: string): string {
  return s.replace(/\s+/g, " ").trim();
}

